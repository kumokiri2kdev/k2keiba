""" Regenerate k2kparser/result_params_data.py from JRA's past result search page.

Run once a year (the table gets the months of the next year around December):
    python tools/update_result_params.py            # fetch from JRA (1 request) and write
    python tools/update_result_params.py --dry-run  # show the changes only
    python tools/update_result_params.py --html FILE  # read a saved page instead of fetching
"""
import argparse
import datetime
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from k2kparser import result_params                 # noqa: E402

DATA_PATH = os.path.join(ROOT, 'k2kparser', 'result_params_data.py')
MIN_ENTRIES = 12 * 30      # sanity check: the table has had every month since 1986


def sort_key(yymm):
    """ '8601' (1986) ... '2612' (2026): sort by year, with 1980s/90s before 2000s. """
    yy = int(yymm[:2])
    return (1900 + yy if yy >= 80 else 2000 + yy), int(yymm[2:])


def render(table, source, fetched_on):
    lines = [
        '""" Table of past result parameters. GENERATED by tools/update_result_params.py - do not edit.',
        '',
        'Source: {}'.format(source),
        'Fetched: {}'.format(fetched_on),
        '"""',
        '',
        '# Months on or after this (YYYYMM) use the "not fixed" prefix (pw01skl00).',
        'YEAR_MONTH = {}'.format(table['year_month']),
        '',
        "# 'YYMM' -> last 2 characters of the CNAME",
        'PARAMS = {',
    ]
    keys = sorted(table['params'], key=sort_key)
    for year in sorted({sort_key(k)[0] for k in keys}):
        row = ['{!r}: {!r},'.format(k, table['params'][k]) for k in keys if sort_key(k)[0] == year]
        lines.append('    ' + ' '.join(row) + '  # {}'.format(year))
    lines.append('}')
    return '\n'.join(lines) + '\n'


def diff(old_params, old_year_month, table):
    new_params = table['params']
    added = sorted(set(new_params) - set(old_params), key=sort_key)
    removed = sorted(set(old_params) - set(new_params), key=sort_key)
    changed = sorted((k for k in new_params if k in old_params and old_params[k] != new_params[k]), key=sort_key)
    print('YEAR_MONTH: {} -> {}'.format(old_year_month, table['year_month']))
    print('entries   : {} -> {}'.format(len(old_params), len(new_params)))
    print('added     : {}'.format(', '.join(added) or '-'))
    print('removed   : {}'.format(', '.join(removed) or '-'))
    print('changed   : {}'.format(', '.join('{} {}->{}'.format(k, old_params[k], new_params[k]) for k in changed) or '-'))
    return bool(added or removed or changed or old_year_month != table['year_month'])


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--dry-run', action='store_true', help='show the changes without writing')
    ap.add_argument('--html', help='parse a saved page instead of fetching from JRA')
    args = ap.parse_args()

    p = result_params.ParserResultParams()
    if args.html:
        with open(args.html, encoding='utf-8') as f:
            table = p.parse_html(f.read())
        source = args.html
    else:
        table = p.parse()
        source = '{}?CNAME={}'.format(p.uri, result_params.SEARCH_PARAM)

    if len(table['params']) < MIN_ENTRIES:
        sys.exit('Too few entries ({}); the page may have changed. Not written.'.format(len(table['params'])))

    from k2kparser import result_params_data as current
    changed = diff(current.PARAMS, current.YEAR_MONTH, table)

    if args.dry_run:
        print('(dry run: not written)')
        return
    if not changed:
        print('No changes.')
        return
    with open(DATA_PATH, 'w', encoding='utf-8') as f:
        f.write(render(table, source, datetime.date.today().isoformat()))
    print('Written: {}'.format(os.path.relpath(DATA_PATH, ROOT)))


if __name__ == '__main__':
    main()
